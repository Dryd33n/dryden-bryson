// Regenerates the CSC 305 WebGL demo pages in public/schoolwork/webgl-scenes/ from the
// assignment repo. Run after changing an assignment's main.html: node scripts/sync-webgl-scenes.mjs
//
// Each page is the assignment's own main.html with its script paths rewritten:
//   - the assignment's .js files load from the repo via jsDelivr, so they stay in sync;
//   - Common/ loads from Angel & Shreiner's published library, pinned to a commit;
//   - compat.js bridges the differences from the course's copy of that library.
// The HTML itself has to be served from this site (jsDelivr serves .html as plain text),
// and so do A2's textures (WebGL can only use same-origin images). The textures in
// scene-2/Textures/ are 1024px copies of the originals.

import { writeFile, mkdir } from 'node:fs/promises';

const repo = 'https://cdn.jsdelivr.net/gh/Dryd33n/uvic-csc-305/Assignments';
const raw = 'https://raw.githubusercontent.com/Dryd33n/uvic-csc-305/HEAD/Assignments';
const common = 'https://cdn.jsdelivr.net/gh/esangel/WebGL@875f0632182d20e531b312d4d5ea0f2ac2004ceb/Common';
const outDir = new URL('../public/schoolwork/webgl-scenes/', import.meta.url);

const scenes = [
  { dir: 'scene-1', assignment: 'A1', title: 'CSC 305 Scene 1: Animated rigs' },
  { dir: 'scene-2', assignment: 'A2', title: 'CSC 305 Scene 2: Textures and firelight' },
];

for (const scene of scenes) {
  const res = await fetch(`${raw}/${scene.assignment}/main.html`);
  if (!res.ok) throw new Error(`${scene.assignment}/main.html: HTTP ${res.status}`);
  let html = await res.text();

  html = html
    .replace(/src="Common\/([^"]+)"/g, (_, file) => `src="${common}/${file}"`)
    .replace(/(<script[^>]*src="[^"]*\/Common\/MV\.js"><\/script>)/, '$1\n<script type="text/javascript" src="../compat.js"></script>')
    .replace(/src="(?!https?:|\.\.\/)([^"]+\.js)"/g, (_, file) => `src="${repo}/${scene.assignment}/${file}"`);

  // Our stylesheet goes last so it can fit the canvas to the frame.
  html = html.replace(/<body>/i, '<link rel="stylesheet" href="../embed.css">\n<body>');

  // Nothing may come before the doctype (that would trigger quirks mode), and the
  // assignment pages have no <head>, so the metadata goes straight after <html>.
  const doctype = html.match(/^\s*<!doctype[^>]*>/i)?.[0].trim() ?? '<!DOCTYPE html>';
  html = html.replace(/^\s*<!doctype[^>]*>/i, '').trimStart();
  const meta = [
    `<!-- Generated by scripts/sync-webgl-scenes.mjs from uvic-csc-305/Assignments/${scene.assignment}/main.html -->`,
    '<meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width, initial-scale=1">',
    `<title>${scene.title}</title>`,
  ].join('\n');
  html = /<html[^>]*>/i.test(html) ? html.replace(/(<html[^>]*>)/i, `$1\n${meta}`) : `${meta}\n${html}`;
  html = `${doctype}\n${html}`;

  await mkdir(new URL(`${scene.dir}/`, outDir), { recursive: true });
  await writeFile(new URL(`${scene.dir}/index.html`, outDir), html);
  console.log(`wrote ${scene.dir}/index.html`);
}
